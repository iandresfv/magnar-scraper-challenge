/** A minimal but structurally valid PDF, large enough to clear the size floor. */
export function syntheticPdf(seed: string): Buffer {
  const filler = `% ${seed} `.repeat(400);
  return Buffer.from(
    `%PDF-1.4\n1 0 obj<</Type/Catalog>>endobj\n${filler}\ntrailer<</Root 1 0 R>>\n%%EOF\n`,
    'latin1',
  );
}

// ───────────────────────────── helpers ─────────────────────────────

function caFor(c: SyntheticCase, epoch: number): string {
  // The token is session-bound: bumping the epoch invalidates every one already issued.
  return `${epoch.toString(16).padStart(4, '0')}${Number(c.idOrigem).toString(16)}`;
}

function resolveCa(dataset: Dataset, ca: string, epoch: number): SyntheticCase | null {
  if (ca.length < 5) return null;
  if (parseInt(ca.slice(0, 4), 16) !== epoch) return null;
  const id = String(parseInt(ca.slice(4), 16));
  return dataset.byId.get(id) ?? null;
}

async function readBody(req: IncomingMessage): Promise<string> {
  if (req.method !== 'POST') return '';
  const chunks: Buffer[] = [];
  for await (const chunk of req) chunks.push(chunk as Buffer);
  // The body arrives latin1-encoded, as the real form does.
  return Buffer.concat(chunks).toString('latin1');
}

function parseForm(body: string): Record<string, string> {
  const fields: Record<string, string> = {};
  for (const pair of body.split('&')) {
    if (pair === '') continue;
    const [rawKey = '', rawValue = ''] = pair.split('=');
    fields[decodeLatin1Component(rawKey)] = decodeLatin1Component(rawValue);
  }
  return fields;
}

/** Percent-decoding that treats each byte as latin1, matching how the form was encoded. */
function decodeLatin1Component(value: string): string {
  return value
    .replace(/\+/g, ' ')
    .replace(/%([0-9a-fA-F]{2})/g, (_, hex: string) => String.fromCharCode(parseInt(hex, 16)));
}

function fold(text: string): string {
  return text.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase().trim();
}

function brToIso(value: string): string {
  const match = /^(\d{2})\/(\d{2})\/(\d{4})$/.exec(value.trim());
  return match === null ? '' : `${match[3] ?? ''}-${match[2] ?? ''}-${match[1] ?? ''}`;
}

function toBrDate(iso: string): string {
  const [y = '', m = '', d = ''] = iso.split('-');
  return `${d}/${m}/${y}`;
}

function toBrDateTime(value: string): string {
  const [date = '', time = '00:00:00'] = value.split(' ');
  return `${toBrDate(date)} ${time}`;
}

function escapeHtml(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
