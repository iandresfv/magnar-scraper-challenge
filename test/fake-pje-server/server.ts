/**
 * A fake PJe, faithful enough to be the system's second site.
 *
 * Two jobs, and the second is the one that matters most:
 *
 * **1. It makes the untestable testable.** Provoking a 429 against a real tribunal would be
 * abusive, and the reconnaissance could not reproduce one within a responsible request budget.
 * Rate limiting is nevertheless an explicit evaluation criterion, so it is implemented in full
 * and proved here — with and without `Retry-After`, alongside 5xx, dropped connections, expired
 * sessions, HTML where a PDF was promised, and truncated PDFs.
 *
 * **2. It keeps the abstraction honest.** This server is registered as a real `SiteAdapter`, so
 * the multi-site claim is exercised by a second implementation rather than asserted by an
 * interface with one. An abstraction with a single implementation is a guess.
 *
 * It reproduces the parts of the real contract the crawler actually depends on: cookies with
 * path scoping, a search action id that is **regenerated on every boot** (so a hardcoded one
 * fails immediately), the row cap with its banner, the empty-result footer with no number, the
 * redirect to a document store, and — measured on the live site — the rejection page the load
 * balancer returns with status 200 for a request carrying an empty `Cookie` header.
 */
import { createServer, type IncomingMessage, type Server, type ServerResponse } from 'node:http';
import type { AddressInfo } from 'node:net';
import { buildDataset, type Dataset, type SyntheticCase } from './dataset.js';

export interface FaultInjection {
  /** Answer the next `times` requests with this status. */
  status?: number;
  /** Seconds to advertise in `Retry-After`. Omitted to test the no-header path. */
  retryAfter?: number;
  /** An HTTP-date instead of seconds, which the spec also allows and clients often mishandle. */
  retryAfterDate?: boolean;
  times?: number;
  /** Delay the response, to exercise timeouts. */
  delayMs?: number;
  /** Destroy the socket without answering. */
  dropConnection?: boolean;
  /** Invalidate every issued `ca`, so the next detail request behaves like a dead session. */
  expireSession?: boolean;
  /** Return an HTML page where a PDF was promised — the real symptom of a lost session. */
  htmlInsteadOfPdf?: boolean;
  /** Cut the PDF short, to exercise the truncation check. */
  truncatePdfAt?: number;
  /** Report a different cap, which must be fatal rather than adaptive. */
  cap?: number;
  /** Turn the captcha hook on, which must stop the run. */
  captcha?: boolean;
  /** Rename the search action id mid-run, as a redeploy would. */
  renameActionId?: boolean;
  /** Serve responses as latin1 instead of UTF-8. */
  latin1?: boolean;
  /** Answer with the load balancer's rejection page, at status 200. */
  wafRejection?: boolean;
}

export interface FakePjeOptions {
  seed?: number;
  days?: number;
  start?: string;
  cap?: number;
  /** Emit the truncation banner. Turned off to prove a full page still forces a split. */
  emitBanner?: boolean;
  /** Fixed port. Zero — the default — lets the OS pick one, which is what tests want. */
  port?: number;
  /** Interface to bind. Loopback by default; a container has to bind all of them. */
  host?: string;
}

export interface FakePjeServer {
  url: string;
  /** The port actually bound, which matters when the requested one was zero. */
  port: number;
  dataset: Dataset;
  /** How many requests have been served, by path kind. */
  counts: Record<string, number>;
  /** Queue a fault for the next matching requests. */
  inject: (fault: FaultInjection) => void;
  clearFaults: () => void;
  /** The action id the current boot expects. Regenerated on `renameActionId`. */
  searchActionId: () => string;
  close: () => Promise<void>;
}

const APP = '/pjeconsulta';

export async function startFakePje(options: FakePjeOptions = {}): Promise<FakePjeServer> {
  const dataset = buildDataset({
    seed: options.seed ?? 20260827,
    days: options.days ?? 90,
    start: options.start ?? '2024-01-01',
    cap: options.cap ?? 30,
  });
  const emitBanner = options.emitBanner ?? true;

  // Autogenerated per boot, exactly as JSF does. A crawler that hardcodes it fails on the first
  // search rather than silently returning nothing.
  let actionId = `fPP:j_id${String(200 + Math.floor(dataset.cases.length % 90))}`;
  let sessionEpoch = 1;
  let pending: FaultInjection | null = null;
  let pendingLeft = 0;
  const counts: Record<string, number> = { list: 0, search: 0, detail: 0, pdf: 0, docstore: 0 };

  const takeFault = (): FaultInjection | null => {
    if (pending === null || pendingLeft <= 0) return null;
    pendingLeft--;
    const fault = pending;
    if (pendingLeft === 0) pending = null;
    return fault;
  };

  const server: Server = createServer((req, res) => {
    void handle(req, res);
  });

  async function handle(req: IncomingMessage, res: ServerResponse): Promise<void> {
    const url = new URL(req.url ?? '/', 'http://localhost');
    const body = await readBody(req);
    const fault = takeFault();

    if (fault?.dropConnection === true) {
      req.socket.destroy();
      return;
    }
    if (fault?.delayMs !== undefined) {
      await new Promise((resolve) => setTimeout(resolve, fault.delayMs));
    }
    if (fault?.expireSession === true) sessionEpoch++;
    if (fault?.renameActionId === true) actionId = `fPP:j_id${String(900 + sessionEpoch)}`;
    if (fault?.status !== undefined) {
      const headers: Record<string, string> = { 'content-type': 'text/html;charset=UTF-8' };
      if (fault.retryAfter !== undefined) {
        headers['retry-after'] =
          fault.retryAfterDate === true
            ? new Date(Date.now() + fault.retryAfter * 1000).toUTCString()
            : String(fault.retryAfter);
      }
      res.writeHead(fault.status, headers);
      res.end(`<html><body>injected ${String(fault.status)}</body></html>`);
      return;
    }
    if (fault?.wafRejection === true) {
      // Status 200 with an error page: measured behaviour of the real load balancer.
      res.writeHead(200, { 'content-type': 'text/html;charset=ISO-8859-1' });
      res.end(Buffer.from('<html><title>Requisição - Rejeitada</title></html>', 'latin1'));
      return;
    }

    // The same measured trap: an *empty* Cookie header is rejected, a missing one is fine.
    if (req.headers.cookie === '') {
      res.writeHead(200, { 'content-type': 'text/html;charset=ISO-8859-1' });
      res.end(Buffer.from('<html><title>Requisição - Rejeitada</title></html>', 'latin1'));
      return;
    }

    const charset = fault?.latin1 === true ? 'latin1' : 'utf8';

    if (url.pathname === `${APP}/ConsultaPublica/listView.seam` && req.method === 'GET') {
      counts['list'] = (counts['list'] ?? 0) + 1;
      res.writeHead(200, {
        'content-type': 'text/html;charset=ISO-8859-1',
        'set-cookie': [
          `JSESSIONID=fake-${String(sessionEpoch)}.node-1; Path=${APP}`,
          'ROUTER_ID=fake; Path=/',
        ],
      });
      res.end(Buffer.from(listViewHtml(actionId, fault?.captcha === true), charset));
      return;
    }

    if (url.pathname === `${APP}/ConsultaPublica/listView.seam` && req.method === 'POST') {
      counts['search'] = (counts['search'] ?? 0) + 1;
      const fields = parseForm(body);
      // The button trap: without the current action id, no search runs.
      if (fields[actionId] === undefined) {
        res.writeHead(200, { 'content-type': 'text/xml;charset=UTF-8' });
        res.end(buttonTrapHtml());
        return;
      }
      const cap = fault?.cap ?? dataset.cap;
      res.writeHead(200, { 'content-type': 'text/xml;charset=UTF-8' });
      res.end(Buffer.from(searchHtml(dataset, fields, cap, emitBanner, sessionEpoch), charset));
      return;
    }

    if (url.pathname.endsWith('/DetalheProcessoConsultaPublica/listView.seam')) {
      counts['detail'] = (counts['detail'] ?? 0) + 1;
      const ca = url.searchParams.get('ca') ?? '';
      const found = resolveCa(dataset, ca, sessionEpoch);
      if (found === null) {
        res.writeHead(302, { location: `${APP}/ConsultaPublica/listView.seam` });
        res.end();
        return;
      }
      res.writeHead(200, { 'content-type': 'text/html;charset=ISO-8859-1' });
      res.end(Buffer.from(detailHtml(found), charset));
      return;
    }

    if (url.pathname.endsWith('/reportPDF.seam')) {
      counts['pdf'] = (counts['pdf'] ?? 0) + 1;
      if (fault?.htmlInsteadOfPdf === true) {
        res.writeHead(200, { 'content-type': 'text/html' });
        res.end('<html><body>sessão expirada</body></html>'.padEnd(4000, ' '));
        return;
      }
      // The real endpoint hands the file over through the document store.
      res.writeHead(302, {
        location: `${APP}/seam/docstore/document.seam?docId=1&cid=${String(Date.now() % 100000)}`,
      });
      res.end();
      return;
    }

    if (url.pathname.endsWith('/reportReciboPDF.seam') || url.pathname.includes('/docstore/')) {
      counts['docstore'] = (counts['docstore'] ?? 0) + 1;
      if (fault?.htmlInsteadOfPdf === true) {
        res.writeHead(200, { 'content-type': 'text/html' });
        res.end('<html><body>sessão expirada</body></html>'.padEnd(4000, ' '));
        return;
      }
      let pdf = syntheticPdf(url.searchParams.get('idProcessoDoc') ?? 'cover');
      if (fault?.truncatePdfAt !== undefined) pdf = pdf.subarray(0, fault.truncatePdfAt);
      res.writeHead(200, {
        'content-type': 'application/pdf',
        'content-length': String(pdf.byteLength),
      });
      res.end(pdf);
      return;
    }

    res.writeHead(404, { 'content-type': 'text/plain' });
    res.end('not found');
  }

  const host = options.host ?? '127.0.0.1';
  await new Promise<void>((resolve) => server.listen(options.port ?? 0, host, resolve));
  const address = server.address() as AddressInfo;

  return {
    url: `http://${host === '0.0.0.0' ? '127.0.0.1' : host}:${String(address.port)}`,
    port: address.port,
    dataset,
    counts,
    inject: (fault) => {
      pending = fault;
      pendingLeft = fault.times ?? 1;
    },
    clearFaults: () => {
      pending = null;
      pendingLeft = 0;
    },
    searchActionId: () => actionId,
    close: () =>
      new Promise<void>((resolve, reject) =>
        server.close((err) => (err === undefined || err === null ? resolve() : reject(err))),
      ),
  };
}

