function buttonTrapHtml(): string {
  // ~2.8 KB in the real site, and crucially it re-renders the message panel, not the grid.
  return `<?xml version="1.0"?><html><head>
<meta name="Ajax-Response" content="true"/><meta name="Ajax-Update-Ids" content="fPP:j_id248"/>
</head><body><span id="fPP:j_id248"></span></body></html>`;
}

function searchHtml(
  dataset: Dataset,
  fields: Record<string, string>,
  cap: number,
  emitBanner: boolean,
  epoch: number,
): string {
  const ini = brToIso(fields['fPP:dataAutuacaoDecoration:dataAutuacaoInicioInputDate'] ?? '');
  const fim = brToIso(fields['fPP:dataAutuacaoDecoration:dataAutuacaoFimInputDate'] ?? '');
  const classeFilter = (fields['fPP:j_id189:classeJudicial'] ?? '').trim();

  let matches: SyntheticCase[] = [];
  for (const [day, cases] of dataset.byDay) {
    if (ini !== '' && day < ini) continue;
    if (fim !== '' && day > fim) continue;
    matches.push(...cases);
  }
  if (classeFilter !== '') {
    // Measured on the real site: the filter is accent-insensitive and matches by **prefix**.
    const needle = fold(classeFilter);
    matches = matches.filter((c) => fold(c.classe).startsWith(needle));
  }
  matches.sort((a, b) => a.numero.localeCompare(b.numero));

  const truncated = matches.length > cap;
  const shown = matches.slice(0, cap);

  const rows = shown
    .map(
      (c) => `<tr class="rich-table-row">
  <td class="rich-table-cell" id="fPP:processosTable:${c.idOrigem}:j_id255">
    <a onclick="openPopUp('Consulta pública','${APP}/ConsultaPublica/DetalheProcessoConsultaPublica/listView.seam?ca=${caFor(c, epoch)}')"></a>
  </td>
  <td class="rich-table-cell" id="fPP:processosTable:${c.idOrigem}:j_id257">${escapeHtml(c.classe)}
    <a onclick="openPopUp('x','${APP}/ConsultaPublica/DetalheProcessoConsultaPublica/listView.seam?ca=${caFor(c, epoch)}')"><b class="btn-block">${c.sigla} ${c.numero} - Assunto</b></a>
    ${escapeHtml(c.parteAtiva)} X ${escapeHtml(c.partePassiva)}
  </td>
  <td class="rich-table-cell" id="fPP:processosTable:${c.idOrigem}:j_id263">${escapeHtml(c.ultimaMovimentacao.descricao)} (${toBrDateTime(c.ultimaMovimentacao.dataHora)})</td>
</tr>`,
    )
    .join('\n');

  const banner =
    truncated && emitBanner
      ? `<div class="alert alert-danger">Sua consulta retornou muitos processos e somente os ${String(cap)} primeiros serão exibidos. Por favor, refine sua pesquisa.</div>`
      : '';

  // With no results the footer renders without a number — the real "empty" marker.
  const count = shown.length === 0 ? '' : String(shown.length);

  return `<?xml version="1.0" encoding="UTF-8"?><html><head>
<meta name="Ajax-Response" content="true"/><meta name="Ajax-Update-Ids" content="fPP:processosGridPanel"/>
</head><body><div id="fPP:processosGridPanel">${banner}
<table id="fPP:processosTable"><tbody>${rows}</tbody>
<tfoot><tr><td><div><div><span class="text-muted">${count} resultados encontrados</span></div></div></td></tr></tfoot>
</table></div></body></html>`;
}

